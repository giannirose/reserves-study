/**
 * convertStudyWorkbook.js — ACTUAL version
 *
 * Reads one uploaded study workbook and returns the four files the pages read:
 *   settings.json          <- Settings tab          (blank values fall back to the example presets)
 *   components.json        <- Components tab        (same rules as xlsx_to_components_json.py)
 *   duesContribution.json  <- Dues Contribution tab (optional; dollars or "10%")
 *   forceInterest.json     <- Force Interest tab    (optional; dollars)
 *
 * Browser: convertStudyWorkbook(uint8Array, XLSX)   Node: convertStudyWorkbook(buffer, XLSX)
 * Requires SheetJS (`xlsx`). Nothing is changed in the data to hide problems: overdue
 * recurring items are reported as warnings and show as negative Remaining Life.
 */

// ---- Example presets: used for any Settings value left blank ----------------
function examplePresets(now = new Date()) {
  const unitCostYear = now.getFullYear();
  return {
    studyName: "Reserve Study",
    associationName: "Example Association",
    unitCostYear,
    studyStartYear: unitCostYear + 1,
    studyLengthYears: 30,
    startingReserveBalance: 100000,
    startingAnnualContribution: 50000,
    generalInflationRatePercent: 3.0,
    interestEarnedRatePercent: 2.0,
    interestTaxRatePercent: 21.0,
    fundingGoalType: "fully_funded",
    fullyFundedTargetPercent: 100,
    currency: "USD",
    fiscalYearStartMonth: 1,
    specialAssessmentAllowed: true,
    loanAllowed: false,
    notes: "",
  };
}

// Same keys, order and types as xlsx_to_settings_json.py's TYPE_MAP
const SETTINGS_TYPES = {
  studyName: "string",
  associationName: "string",
  unitCostYear: "integer",
  studyStartYear: "integer",
  studyLengthYears: "integer",
  startingReserveBalance: "integer",
  startingAnnualContribution: "integer",
  generalInflationRatePercent: "float",
  interestEarnedRatePercent: "float",
  interestTaxRatePercent: "float",
  fundingGoalType: "string",
  fullyFundedTargetPercent: "integer",
  currency: "string",
  fiscalYearStartMonth: "integer",
  specialAssessmentAllowed: "boolean",
  loanAllowed: "boolean",
  notes: "string",
};
const PERCENT_SETTINGS = new Set(["generalInflationRatePercent", "interestEarnedRatePercent",
  "interestTaxRatePercent", "fullyFundedTargetPercent"]);

const STUDY_COLUMNS = [
  ["Component ID", "id"],
  ["Category", "category"],
  ["Name", "name"],
  ["Item Type", "itemType"],
  ["Date In Service", "dateInService"],
  ["Useful Life (Years)", "usefulLifeYears"],
  ["Adjustment (Years)", "adjustmentYears"],
  ["Scope Factor", "scopeFactor"],
  ["Quantity", "quantity"],
  ["Quantity Unit", "quantityUnit"],
  ["Unit Cost ($)", "unitCost"],
  ["Notes", "notes"], 
];

const COMPONENTS_SCHEMA_NOTES = "All dollar amounts are in whole dollars (not cents). 'recurring' items repeat every usefulLifeYears after their first scheduled occurrence; 'one-time' items occur once. The FIRST scheduled occurrence for any item is dateInService + usefulLifeYears + adjustmentYears. adjustmentYears is a YEAR COUNT, not a percent, and may be POSITIVE (serviced later than the standard formula predicts) or NEGATIVE (serviced earlier). It corrects only the first/current scheduled cycle to match observed real-world history — it does NOT apply to any future recurrence. If a recurring component's actual replacement interval ever differs from usefulLifeYears, update usefulLifeYears directly during the study's annual review rather than tracking a separate cycle length. scopeFactor defaults to 1 when not used. A component with unitCost set to null (not yet priced) is intentionally excluded from every dollar total across all pages until priced. funded: false marks a component the association has deliberately chosen not to fund from reserves; it keeps its unitCost for reference but is excluded from every total, and a missing funded key means funded. Generated by convertStudyWorkbook.js from the Components tab of the uploaded workbook.";

// ---- Cell helpers -------------------------------------------------------------
// Marks around a component name in messages. The upload page shows the marked text in
// italics; the command line removes the marks. Invisible characters, so they never
// clash with anything typed in a workbook.
const NAME_START = "\u0001";
const NAME_END = "\u0002";
const markName = (n) => `${NAME_START}${n}${NAME_END}`;
const stripNameMarks = (s) => String(s).replace(/[\u0001\u0002]/g, "");

const blank = (v) => v === null || v === undefined || (typeof v === "string" && v.trim() === "");
const str = (v) => (blank(v) ? "" : String(v).trim());

/** True when a cell's number format is a real Excel percent (value stored as 0.03 for 3%). */
function isPercentFormat(cell) {
  return !!(cell && cell.t === "n" && cell.z && /%/.test(String(cell.z).replace(/"[^"]*"/g, "")));
}

function parseNumber(v) {
  if (typeof v === "number") return v;
  if (blank(v)) return null;
  const n = Number(String(v).replace(/[$,\s]/g, ""));
  return Number.isFinite(n) ? n : NaN;
}

function findSheet(wb, name) {
  const key = name.toLowerCase();
  const found = wb.SheetNames.find((n) => n.trim().toLowerCase() === key);
  return found ? { name: found, ws: wb.Sheets[found] } : null;
}

/** Rows of { value, cell } for a sheet; cell gives access to its number format. */
function sheetGrid(XLSX, ws) {
  if (!ws || !ws["!ref"]) return [];
  const range = XLSX.utils.decode_range(ws["!ref"]);
  const grid = [];
  for (let r = range.s.r; r <= range.e.r; r++) {
    const row = [];
    for (let c = range.s.c; c <= range.e.c; c++) {
      const cell = ws[XLSX.utils.encode_cell({ r, c })];
      row.push({ value: cell ? cell.v : null, cell });
    }
    grid.push(row);
  }
  return grid;
}

// ---- Settings tab -------------------------------------------------------------
function readSettings(XLSX, wb, report, now) {
  const presets = examplePresets(now);
  const found = findSheet(wb, "Settings");
  const entered = {};
  if (!found) {
    report.warnings.push("No Settings tab was found, so every setting uses the example value.");
  } else {
    const grid = sheetGrid(XLSX, found.ws);
    const header = (grid[0] || []).map((c) => str(c.value).toLowerCase());
    const keyCol = header.indexOf("json key");
    const valCol = header.indexOf("value");
    if (keyCol === -1 || valCol === -1) {
      report.errors.push('Settings tab: the first row must include "JSON Key" and "Value" columns.');
      return null;
    }
    const seen = new Set();
    grid.slice(1).forEach((row, i) => {
      const rowNum = i + 2;
      const key = str(row[keyCol] && row[keyCol].value);
      if (!key) return;
      if (!(key in SETTINGS_TYPES)) {
        report.warnings.push(`Settings row ${rowNum}: "${key}" is not a recognized setting and was ignored.`);
        return;
      }
      if (seen.has(key)) report.warnings.push(`Settings row ${rowNum}: "${key}" appears twice; the later row is used.`);
      seen.add(key);
      const { value, cell } = row[valCol] || {};
      if (blank(value)) return;
      const type = SETTINGS_TYPES[key];
      const bad = (what) => report.errors.push(`Settings row ${rowNum} (${key}): expected ${what}, found "${value}".`);
      if (type === "string") {
        entered[key] = str(value);
      } else if (type === "boolean") {
        if (typeof value === "boolean") entered[key] = value;
        else if (/^(true|yes)$/i.test(str(value))) entered[key] = true;
        else if (/^(false|no)$/i.test(str(value))) entered[key] = false;
        else bad("TRUE or FALSE");
      } else {
        let n = parseNumber(typeof value === "string" ? value.replace(/%$/, "") : value);
        if (n === null || Number.isNaN(n)) return bad("a number");
        if (PERCENT_SETTINGS.has(key) && isPercentFormat(cell)) n = Math.round(n * 100 * 1e6) / 1e6;   // typed 3% -> stored 0.03 -> 3
        if (type === "integer") {
          if (!Number.isInteger(Math.round(n * 1e6) / 1e6)) {
            if (key === "startingReserveBalance" || key === "startingAnnualContribution") n = Math.round(n);
            else return bad("a whole number");
          }
          n = Math.round(n);
        }
        entered[key] = n;
      }
    });
  }

  // Years: derive one from the other when only one is given
  if (entered.unitCostYear === undefined && entered.studyStartYear !== undefined) presets.unitCostYear = entered.studyStartYear - 1;
  if (entered.studyStartYear === undefined && entered.unitCostYear !== undefined) presets.studyStartYear = entered.unitCostYear + 1;

  const settings = {};
  const filled = [];
  for (const key of Object.keys(SETTINGS_TYPES)) {
    if (entered[key] !== undefined) settings[key] = entered[key];
    else {
      settings[key] = presets[key];
      if (key !== "notes") filled.push(`${key} = ${JSON.stringify(presets[key])}`);
    }
  }
  if (filled.length) report.notices.push(`Settings left blank use the example values: ${filled.join(", ")}.`);

  // Sanity checks
  const s = settings;
  const err = (m) => report.errors.push(`Settings: ${m}`);
  const warn = (m) => report.warnings.push(`Settings: ${m}`);
  if (s.studyStartYear < 1900 || s.studyStartYear > 2200) err(`Study Start Year ${s.studyStartYear} is not a valid year.`);
  if (s.unitCostYear > s.studyStartYear) err(`Study Planning Year (${s.unitCostYear}) is after the Study Start Year (${s.studyStartYear}).`);
  else if (s.studyStartYear - s.unitCostYear > 1) warn(`Unit costs are priced in ${s.unitCostYear}, ${s.studyStartYear - s.unitCostYear} years before the study starts. Typical is the year before.`);
  if (s.studyLengthYears < 1 || s.studyLengthYears > 100) err(`Study Length ${s.studyLengthYears} must be between 1 and 100 years.`);
  if (s.generalInflationRatePercent > 0 && s.generalInflationRatePercent < 0.2) warn(`General Inflation Rate is ${s.generalInflationRatePercent}%. Enter 3 for 3%, not 0.03.`);
  if (s.interestEarnedRatePercent > 0 && s.interestEarnedRatePercent < 0.2) warn(`Interest Earned Rate is ${s.interestEarnedRatePercent}%. Enter 2 for 2%, not 0.02.`);
  if (s.generalInflationRatePercent > 15) warn(`General Inflation Rate is ${s.generalInflationRatePercent}%, well above the typical 2.5 to 4.`);
  if (s.interestTaxRatePercent < 0 || s.interestTaxRatePercent > 100) err(`Interest Tax Rate must be between 0 and 100.`);
  if (s.fiscalYearStartMonth < 1 || s.fiscalYearStartMonth > 12) err(`Fiscal Year Start Month must be 1 to 12.`);
  return settings;
}

// ---- Components tab -----------------------------------------------------------
function readComponents(XLSX, wb, settings, report) {
  const found = findSheet(wb, "Components");
  if (!found) { report.errors.push("No Components tab was found."); return null; }
  const rows = XLSX.utils.sheet_to_json(found.ws, { header: 1, raw: true, defval: null, blankrows: true });
  const header = (rows[0] || []).map((h) => str(h).toLowerCase());
  const col = {};
  for (const [label, key] of STUDY_COLUMNS) {
    const i = header.indexOf(label.toLowerCase());
    if (i === -1) report.errors.push(`Components tab: missing column "${label}".`);
    else col[key] = i;
  }
  if (Object.keys(col).length !== STUDY_COLUMNS.length) return null;
  // Funding is optional, so workbooks made before it existed still load (everything counts as funded)
  const fundingCol = header.indexOf("funding");
  const inflationCol = header.indexOf("inflation rate");

  const components = [];
  const seen = new Map();
  const unpriced = [];
  const unfunded = [];
  rows.slice(1).forEach((row, i) => {
    const rowNum = i + 2;
    const get = (k) => row[col[k]];

    const id = str(get("id"));
    const name = str(get("name"));
    if (!id && !name) return;                       // empty or leftover formatting row
    // e.g. "Components row 9 (pave-001; *Asphalt Pavement - Clean and Seal*)", name in italics on the upload page
    const label = [id, name ? markName(name) : ""].filter(Boolean).join("; ");
    const where = `Components row ${rowNum}${label ? ` (${label})` : ""}`;
    const rowErr = (m) => report.errors.push(`${where}: ${m}`);
    const rowWarn = (m) => report.warnings.push(`${where}: ${m}`);

    const num = (key, label, { required = false, def = null, integer = false } = {}) => {
      const raw = get(key);
      const v = parseNumber(raw);
      if (v === null) { if (required) rowErr(`${label} is required.`); return def; }
      if (Number.isNaN(v)) { rowErr(`${label} "${raw}" is not a number.`); return def; }
      if (integer && !Number.isInteger(v)) { rowErr(`${label} must be a whole number.`); return def; }
      return v;
    };

    const itemType = str(get("itemType")).toLowerCase();
    const c = {
      id,
      category: str(get("category")) || null,
      name,
      itemType,
      dateInService: num("dateInService", "Date In Service", { required: true, integer: true }),
      usefulLifeYears: num("usefulLifeYears", "Useful Life", { required: true, integer: true }),
      adjustmentYears: num("adjustmentYears", "Adjustment", { def: 0, integer: true }),
      scopeFactor: num("scopeFactor", "Scope Factor", { def: 1 }),
      quantity: num("quantity", "Quantity", { def: 1 }),
      quantityUnit: str(get("quantityUnit")) || null,
      unitCost: num("unitCost", "Unit Cost"),
      funded: true,
      notes: str(get("notes")),
      inflationRate: null,   // filled in below
    };

    // Funding: blank or "Funded" = counted; "Unfunded" = deliberately not funded (listed, left out of all totals)
    const fundingRaw = fundingCol === -1 ? "" : str(row[fundingCol]);
    if (/^unfunded$/i.test(fundingRaw)) c.funded = false;
    else if (fundingRaw && !/^funded$/i.test(fundingRaw)) rowErr(`Funding is "${fundingRaw}"; expected Funded, Unfunded or blank.`);
        // ↓ ADD THIS BLOCK HERE ↓
    // Per-component inflation rate (optional — blank falls back to global rate)
    if (inflationCol !== -1) {
      const raw = row[inflationCol];
      if (raw !== null && raw !== "") {
        const cell = found.ws[XLSX.utils.encode_cell({ r: i + 1, c: inflationCol })];
        let pct;
        if (isPercentFormat(cell)) {
          pct = parseNumber(raw) * 100;
        } else {
          pct = parseNumber(raw);
        }
        if (pct === null || Number.isNaN(pct)) {
          rowErr(`Inflation Rate "${raw}" is not a number.`);
        } else if (pct < 0) {
          rowWarn(`Inflation Rate is negative (${pct}%). This is allowed but unusual.`);
          c.inflationRate = pct;
        } else {
          c.inflationRate = pct;
        }
      }
    }
    // ↑ END OF NEW BLOCK ↑
    const shortName = id && name ? `${id} (${markName(name)})` : id || markName(name);

    if (!id) rowErr("Component ID is required.");
    else if (seen.has(id)) rowErr(`Component ID duplicates row ${seen.get(id)}.`);
    else seen.set(id, rowNum);
    if (!name) rowErr("Name is required.");
    if (!c.category) rowErr("Category is required.");
    if (!["recurring", "one-time"].includes(itemType)) rowErr(`Item Type is "${str(get("itemType"))}"; expected recurring or one-time.`);
    if (c.usefulLifeYears !== null && c.usefulLifeYears < 1) rowErr("Useful Life must be at least 1 year.");
    if (c.scopeFactor !== null && !(c.scopeFactor > 0 && c.scopeFactor <= 1)) rowWarn(`Scope Factor is ${c.scopeFactor}, outside the usual range above 0 up to 1. Confirm it is intended.`);
    if (c.quantity !== null && c.quantity <= 0) rowErr("Quantity must be greater than 0.");
    if (c.unitCost !== null && c.unitCost < 0) rowWarn(`Unit Cost is negative (${c.unitCost}). If this is a credit or rescinded charge, it will be included in calculations as-is.`);
    if (!c.funded) unfunded.push(shortName);
    else if (c.unitCost === null) unpriced.push(shortName);
    if (c.funded && /unfunded/i.test(`${name} ${c.notes}`)) {
      rowWarn(`${/unfunded/i.test(name) ? "its Name says" : "its Notes say"} "Unfunded", but the Funding column is not set to Unfunded. ` +
        `If the association has chosen not to fund it, set Funding to Unfunded so it is listed as unfunded rather than ` +
        `${c.unitCost === null ? "as not yet priced" : "counted in the totals"}.`);
    }

    // Overdue / already-past items: reported, not changed (not needed for unfunded items)
    if (c.funded && c.dateInService !== null && c.usefulLifeYears && c.adjustmentYears !== null) {
      const first = c.dateInService + c.usefulLifeYears + c.adjustmentYears;
      const start = settings.studyStartYear;
      const end = start + settings.studyLengthYears - 1;
      if (first < start) {
        if (itemType === "recurring") {
          let next = first;
          while (next < start) next += c.usefulLifeYears;
          const shown = `first scheduled cycle ${first} is before the Study Start Year (${start}), so Remaining Life shows ${first - start} years.`;
          // Last on-schedule cycle before the study: if the work has been done on time,
          // that is the real Date In Service, with Adjustment back to 0.
          const lastDone = next - c.usefulLifeYears;
          const onSchedule = `If it has been done on schedule, set Date In Service to ${lastDone} and Adjustment to 0` +
            ` (next due ${next <= end ? next : "after the study ends"}; Remaining Life ${next - start}).`;
          if (next === start) {
            rowWarn(`${shown} ${onSchedule}`);
          } else {
            rowWarn(`${shown} ${onSchedule} If the work is still outstanding, ` +
              `set Adjustment to ${c.adjustmentYears + (start - first)} to schedule it in ${start}.`);
          }
        } else if (itemType === "one-time") {
          rowWarn(`one-time item scheduled for ${first}, before the Study Start Year (${start}), so it will not appear in the study.`);
        }
      }
    }
    components.push(c);
  });

  if (!components.length) report.errors.push("Components tab: no components were entered.");
if (unfunded.length) report.notices.push(`Unfunded by choice, excluded from all totals: ${unfunded.length} item${unfunded.length === 1 ? "" : "s"} — see the full list on the Categorized Components page.`);
  if (unpriced.length) report.notices.push(`Not yet priced (no Unit Cost), so left out of all totals: ${unpriced.join(", ")}.`);
  return { schemaNotes: COMPONENTS_SCHEMA_NOTES, components };
}

// ---- Dues Contribution / Force Interest tabs ------------------------------------
function readOverrides(XLSX, wb, sheetName, { allowPercent, twoColumn, settings, report, label }) {
  const result = { overrides: {} };
  const found = findSheet(wb, sheetName);
  if (!found) return result;
  const grid = sheetGrid(XLSX, found.ws);
  let headerRow = -1;
  grid.forEach((row, r) => {
    const a = str(row[0] && row[0].value);
    if (a === "Year" && headerRow === -1) headerRow = r;
  });
  if (headerRow === -1) {
    report.errors.push(`${sheetName} tab: could not find the overrides table (a row starting with "Year").`);
    return result;
  }
  const start = settings.studyStartYear;
  const end = start + settings.studyLengthYears - 1;
  for (let r = headerRow + 1; r < grid.length; r++) {
    const row = grid[r];
    const yearRaw = row[0] && row[0].value;
    if (blank(yearRaw)) continue;
    const rowNum = r + 1;
    const where = `${sheetName} row ${rowNum}`;
    const year = parseNumber(yearRaw);
    if (year === null || Number.isNaN(year) || !Number.isInteger(year)) {
      report.errors.push(`${where}: Year "${yearRaw}" is not a 4-digit year.`);
      continue;
    }

    let out;

    if (twoColumn) {
      const dollarVal = row[1] && row[1].value;
      const pctCell   = row[2] || {};
      const pctVal    = pctCell.value;
      const hasDollar = !blank(dollarVal);
      const hasPct    = !blank(pctVal);

      if (hasDollar && hasPct) {
        report.errors.push(`${where} (${year}): both a dollar amount and a percent change are entered — use one or the other.`);
        continue;
      }
      if (!hasDollar && !hasPct) {
        report.warnings.push(`${where} (${year}): no ${label} entered, so the row was skipped.`);
        continue;
      }
      if (hasDollar) {
        const n = parseNumber(dollarVal);
        if (n === null || Number.isNaN(n)) {
          report.errors.push(`${where} (${year}): "${dollarVal}" is not a valid dollar amount.`);
          continue;
        }
        out = Math.round(n);
      } else {
        if (isPercentFormat(pctCell.cell)) {
          out = `${Math.round(pctVal * 100 * 1e6) / 1e6}%`;
        } else if (typeof pctVal === "string" && /%\s*$/.test(pctVal)) {
          const n = parseNumber(pctVal.replace(/%\s*$/, ""));
          if (n === null || Number.isNaN(n)) {
            report.errors.push(`${where} (${year}): "${pctVal}" is not a valid percent.`);
            continue;
          }
          out = `${n}%`;
        } else {
          const n = parseNumber(pctVal);
          if (n === null || Number.isNaN(n)) {
            report.errors.push(`${where} (${year}): "${pctVal}" is not a valid percent.`);
            continue;
          }
          out = `${n}%`;
        }
      }
    } else {
      const { value, cell } = row[1] || {};
      if (blank(value)) {
        report.warnings.push(`${where} (${year}): no ${label} entered, so the row was skipped.`);
        continue;
      }
      if (allowPercent && isPercentFormat(cell)) {
        out = `${Math.round(value * 100 * 1e6) / 1e6}%`;
      } else if (allowPercent && typeof value === "string" && /%\s*$/.test(value)) {
        const pct = parseNumber(value.replace(/%\s*$/, ""));
        if (pct === null || Number.isNaN(pct)) {
          report.errors.push(`${where} (${year}): "${value}" is not a valid percent.`);
          continue;
        }
        out = `${pct}%`;
      } else {
        const n = parseNumber(value);
        if (n === null || Number.isNaN(n)) {
          report.errors.push(`${where} (${year}): "${value}" is not a valid amount.`);
          continue;
        }
        out = allowPercent ? Math.round(n) : Math.round(n * 100) / 100;
        if (!allowPercent && n < 0) {
          report.warnings.push(`${where} (${year}): negative interest is counted as $0.`);
        }
      }
    }

    if (year < start || year > end) {
      report.warnings.push(`${where}: ${year} is outside the study years (${start}–${end}), so it has no effect.`);
    }
    if (Object.prototype.hasOwnProperty.call(result.overrides, String(year))) {
      report.warnings.push(`${where}: ${year} is listed more than once; the later row is used.`);
    }
    result.overrides[String(year)] = out;
  }
  return result;
}

// ---- Main ------------------------------------------------------------------------
function convertStudyWorkbook(data, XLSX, options = {}) {
  const report = { errors: [], warnings: [], notices: [] };
  const type = options.type || (typeof Buffer !== "undefined" && Buffer.isBuffer(data) ? "buffer" : "array");
  const wb = XLSX.read(data, { type, cellNF: true });

  const settings = readSettings(XLSX, wb, report, options.now);
  const components = settings ? readComponents(XLSX, wb, settings, report) : null;
const duesContribution = settings
  ? readOverrides(XLSX, wb, "Dues Contribution", { allowPercent: true, twoColumn: true, settings, report, label: "contribution" })
  : null;
  const forceInterest = settings
    ? readOverrides(XLSX, wb, "Force Interest", { allowPercent: false, settings, report, label: "interest amount" })
    : null;

  const ok = report.errors.length === 0 && !!settings && !!components;
  return {
    ok,
    ...report,
    settings: ok ? settings : null,
    components: ok ? components : null,
    duesContribution: ok ? duesContribution : null,
    forceInterest: ok ? forceInterest : null,
  };
}

