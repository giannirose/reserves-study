// CLI: node convertStudyWorkbook.js workbook.xlsx [outputFolder]
//   writes settings.json, components.json, duesContribution.json, forceInterest.json
if (typeof require !== "undefined" && require.main === module) {
  const fs = require("fs");
  const path = require("path");
  const XLSX = require("xlsx");
  const [input, outDir = "."] = process.argv.slice(2);
  if (!input) { console.error("Usage: node convertStudyWorkbook.js workbook.xlsx [outputFolder]"); process.exit(2); }
  const r = convertStudyWorkbook(fs.readFileSync(input), XLSX);
  r.notices.forEach((m) => console.log("Note:", stripNameMarks(m)));
  r.warnings.forEach((m) => console.warn("Warning:", stripNameMarks(m)));
  if (!r.ok) { r.errors.forEach((m) => console.error("Error:", stripNameMarks(m))); process.exit(1); }
  fs.mkdirSync(outDir, { recursive: true });
  for (const name of ["settings", "components", "duesContribution", "forceInterest"]) {
    fs.writeFileSync(path.join(outDir, `${name}.json`), JSON.stringify(r[name], null, 2));
  }
  console.log(`Wrote settings.json, components.json (${r.components.components.length} components), ` +
    `duesContribution.json (${Object.keys(r.duesContribution.overrides).length} years), ` +
    `forceInterest.json (${Object.keys(r.forceInterest.overrides).length} years) to ${outDir}`);
}
